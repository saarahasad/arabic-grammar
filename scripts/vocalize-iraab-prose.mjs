// require that the stem is followed by a space, punctuation or end-of-string.
const WAW_GLUE_RE = new RegExp(
  `(^|[\\s«﴿،؛.])و\\s+(?=(?:${WAW_GLUE_STEMS.join('|')})(?![\\u0621-\\u063A\\u0641-\\u064A\\u064B-\\u065F\\u0670\\u0640]))`,
  'g'
);

/** Apply the dictionary across one prose chunk (no quoted fragments). */
function vocalizeProseChunk(chunk) {
  const glued = chunk.replace(WAW_GLUE_RE, '$1و');
  return glued.replace(COMPILED.composite, (match) => {
    const key = stripHarakah(match).replace(/\s+/g, ' ').trim();
    return COMPILED.lookup.get(key) || match;
  });
}

/**
 * Replace iʿrāb terminology with fully vocalized forms.
 *
 * - Preserves quoted Qurʾānic text inside "…", French «…», and ornamental
 *   brackets ﴿…﴾.
 * - Splits each prose run into sentence-sized chunks (split on . ، ؛ \n) so a
 *   mixed string ("first clause fully vocalized، second clause not") gets
 *   correctly vocalized clause-by-clause.
 * - Each chunk is vocalized only if it is *not* already substantially marked,
 *   so curator-vocalized prose is never overwritten.
 */
export function vocalizeIraabProse(text) {
  if (!text) return text;
  const input = String(text);
  if (!input.trim()) return input;

  // Split out quoted Qurʾānic fragments so the dictionary does not eat them.
  const tokens = [];
  const RE_QUOTED = /("[^"]*"|«[^»]*»|﴿[^﴾]*﴾)/g;
  let lastIdx = 0;
  let m;
  while ((m = RE_QUOTED.exec(input)) !== null) {
    if (m.index > lastIdx) tokens.push({ kind: 'prose', text: input.slice(lastIdx, m.index) });
    tokens.push({ kind: 'quote', text: m[0] });
    lastIdx = m.index + m[0].length;
  }
  if (lastIdx < input.length) tokens.push({ kind: 'prose', text: input.slice(lastIdx) });

  return tokens
    .map((tok) => {
      if (tok.kind === 'quote') return tok.text;
      // Re-split prose on sentence delimiters (period, Arabic comma/semicolon,
      // newline). Keep delimiters via capture-group split so output is identical.
      const parts = tok.text.split(/([،؛.\n])/);
      return parts
        .map((part) => {
          if (!part || /^[،؛.\n]$/.test(part)) return part;
          if (isAlreadyVocalized(part)) return part;
          return vocalizeProseChunk(part);
        })
        .join('');
    })
    .join('');
}

// CLI helper: `node scripts/vocalize-iraab-prose.mjs "<text>"`
if (import.meta.url === `file://${process.argv[1]}`) {
  const arg = process.argv.slice(2).join(' ');
  if (!arg) {
    console.log('Usage: node scripts/vocalize-iraab-prose.mjs "<iʿrāb prose>"');
    process.exit(0);
  }
  process.stdout.write(vocalizeIraabProse(arg) + '\n');
}
