function stripHarakah(s) {
  return String(s == null ? '' : s).replace(STRIP_HARAKAH_RE, '');
}

function escapeRe(ch) {
  return ch.replace(/[-/\\^$*+?.()|[\]{}]/g, '\\$&');
}

/** Build a regex body that matches `stripped` with optional ḥarakāt between letters. */
function bodyFor(stripped) {
  return stripped
    .split('')
    .map((ch) => {
      if (ch === ' ') return '\\s+';
      return escapeRe(ch) + '[\\u064B-\\u065F\\u0670\\u0640]*';
    })
    .join('');
}

/**
 * One pre-computed composite alternation regex. Entries are sorted by stripped
 * length descending so longer phrases win at any given position (JS regex
 * alternation tries alternatives left-to-right).
 *
 * After a match, we look up the corresponding replacement by stripping the
 * match back to its tashkīl-free form and using the dictionary map.
 */
const COMPILED = (() => {
  const cleaned = ENTRIES.map(([k, v]) => [
    stripHarakah(k).replace(/\s+/g, ' ').trim(),
    v,
  ]).sort((a, b) => b[0].length - a[0].length);

  const lookup = new Map(cleaned);
  const composite = new RegExp(
    `(?<!${WORD_CHAR})(?:${cleaned.map(([k]) => bodyFor(k)).join('|')})(?!${WORD_CHAR})`,
    'gu'
  );
  return { lookup, composite };
})();

/**
 * If the text already carries substantial ḥarakāt, leave it alone — re-running
 * the dictionary on already-vocalized prose is risky because words like
 * مَرْفُوع / خَبَر may be in non-default cases that depend on syntactic context.
 *
 * Heuristic: ratio of harakah marks per Arabic letter. Lightly-vocalized
 * inputs (just shaddah here and there) stay below the threshold; fully
 * vocalized text passes it and is preserved verbatim.
 */
function isAlreadyVocalized(text) {
  const letters = (text.match(/[\u0621-\u063A\u0641-\u064A]/g) || []).length;
  if (!letters) return true;
  const marks = (text.match(/[\u064B-\u0652\u0670]/g) || []).length;
  return marks / letters > 0.35;
}

